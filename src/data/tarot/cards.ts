function minorLabel(n: number): string {
  if (n === 1) return 'Ace'
  if (n === 11) return 'Page'
  if (n === 12) return 'Knight'
  if (n === 13) return 'Queen'
  if (n === 14) return 'King'
  return String(n)
}

function minorId(n: number, suit: TarotSuit): string {
  return `${minorLabel(n).toLowerCase()}-of-${suit}`
}

function minorName(n: number, suit: TarotSuit): string {
  const capSuit = suit.charAt(0).toUpperCase() + suit.slice(1)
  return `${minorLabel(n)} of ${capSuit}`
}

